  all(projectId) {
    const extra = this[projectId] || [];
    const map = new Map();
    for (const t of [...this.SHARED, ...extra]) {
      if (!t || !t.term) continue;
      const key = String(t.term).toLowerCase();
      if (!map.has(key)) map.set(key, t);
    }
    return Array.from(map.values()).sort((a, b) => b.term.length - a.term.length);
  },

  find(term, projectId) {
    const key = String(term || "")
      .toLowerCase()
      .replace(/ё/g, "е")
      .trim();
    if (!key) return null;
    return (
      this.all(projectId).find((t) => String(t.term).toLowerCase().replace(/ё/g, "е") === key) || null
    );
  },

  mark(escapedText, projectId) {
    let html = String(escapedText || "");
    for (const t of this.all(projectId)) {
      const raw = String(t.term);
      const re = new RegExp(
        "(^|[^\\wа-яёА-ЯЁ])(" + this.escapeReg(raw) + ")(?=[^\\wа-яёА-ЯЁ]|$)",
        "gi"
      );
      html = html.replace(re, (full, pre, m) => {
        return (
          pre +
          `<button type="button" class="gloss-term" data-gloss="${this.escapeAttr(raw)}">${m}</button>`
        );
      });
    }
    return html;
  },

  escapeReg(s) {
    return String(s).replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  },

  escapeAttr(s) {
    return String(s)
      .replace(/&/g, "&amp;")
      .replace(/"/g, "&quot;")
      .replace(/</g, "&lt;")
      .replace(/>/g, "&gt;");
  },

  linesForDoc(projectId) {
    return this.all(projectId).map((t) => `${t.term} — ${t.def}`);
  },
